# Builds en_US.py: American English for School Connect, following Gibbon's en_US file:
#   Form Group -> Homeroom, Markbook -> Gradebook, Behaviour -> Behavior,
#   Enrol(ment) -> Enroll(ment), Licence -> License, -ise -> -ize, Colour -> Color,
#   Cancelled -> Canceled, Centre -> Center, Programme -> Program, Maths -> Math.
# Only strings that change are written; everything else falls back to the English.
import re, json, pprint, polib

RULES = [
    (r'\bForm Group(s?)\b', r'Homeroom\1'), (r'\bform group(s?)\b', r'homeroom\1'),
    (r'\bMarkbook(s?)\b', r'Gradebook\1'), (r'\bmarkbook(s?)\b', r'gradebook\1'),
    (r'\b([Bb])ehaviour', r'\1ehavior'),
    (r'\b([Ee])nrolment', r'\1nrollment'), (r'\b([Ee])nrol(s|able)?\b', r'\1nroll\2'),
    (r'\b([Uu])nenrol\b', r'\1nenroll'), (r'\b([Rr])e-[Ee]nrol\b', r'\1e-Enroll'),
    (r'\b([Ll])icence\b', r'\1icense'),
    (r'\b([Cc])olour', r'\1olor'),
    (r'\b([Oo])rganis', r'\1rganiz'),
    (r'\b(Customi|customi|Prioriti|prioriti|Authori|authori|Summari|summari|Finali|finali|Recogni|recogni|Personali|personali|Visuali|visuali|Categori|categori)s(e|ed|es|ing|ation)\b', r'\1z\2'),
    (r'\b([Aa])nalys(e|ed|es|ing)\b', r'\1nalyz\2'),
    (r'\b([Cc])ancell(ed|ing)\b', r'\1ancel\2'),
    (r'\b([Cc])entre(s?)\b', r'\1enter\2'),
    (r'\b([Pp])rogramme(s?)\b', r'\1rogram\2'),
    (r'\bMaths\b', 'Math'),
    (r'\b([Cc])atalogue', r'\1atalog'),
    (r'\b([Ff])avourite', r'\1avorite'),
]
def us(s):
    for a, b in RULES:
        s = re.sub(a, b, s)
    return s

S = '/tmp/claude-0/-home-claude/ed44e25e-8ea3-50fe-9e70-472e23db17dc/scratchpad/'
pot = polib.pofile(S + 'all.pot')
module = {e.msgid for e in polib.pofile(S + 'School Connect.pot')}
gib = {e.msgid: e for e in polib.mofile('/home/claude/gibbon-i18n/en_US/LC_MESSAGES/gibbon.mo') if e.msgid}

T, P, GAPS = {}, {}, {}
for e in pot:
    if e.msgid_plural:
        a, b = us(e.msgid), us(e.msgid_plural)
        if (a, b) != (e.msgid, e.msgid_plural):
            if e.msgid in module: P[e.msgid] = (a, b)
            elif e.msgid not in gib: GAPS[e.msgid] = (a, b)
        continue
    v = us(e.msgid)
    if v == e.msgid: continue
    if e.msgid in module: T[e.msgid] = v
    elif e.msgid not in gib: GAPS[e.msgid] = v      # Gibbon string its en_US file lacks

EXTRA = {}
with open(S + 'en_US.py', 'w', encoding='utf-8') as f:
    f.write('# American English (en_US) for School Connect, generated by make_en_US.py from the\n'
            "# English text, following Gibbon's en_US file (Homeroom, Gradebook, Behavior, Enrollment).\n"
            '# Only strings that change; the app shows its English text for everything else.\n'
            'SPARSE = True\n\n')
    for name, d in (('T', T), ('P', P), ('EXTRA', EXTRA), ('GAPS', {k: v for k, v in GAPS.items() if isinstance(v, str)}), ('OVERRIDES', {})):
        f.write(f'{name} = ' + pprint.pformat(d, width=200, sort_dicts=True) + '\n\n')
print(f'T {len(T)}  P {len(P)}  GAPS {len(GAPS)}')
for d in (T, P, GAPS):
    for k, v in d.items(): print(f'  {k!r} -> {v!r}')
